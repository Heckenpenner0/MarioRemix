#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn sprite_rows_consistent() {
        let all: &[(&str, Spr)] = &[
            ("ms", M_SMALL_STAND), ("mb", M_BIG_STAND), ("dive", M_DIVE),
            ("goomba", E_GOOMBA1), ("koopa", E_KOOPA1), ("shell", E_SHELL),
            ("pir", E_PIR_OPEN), ("spiny", E_SPINY), ("bat", E_BAT1),
            ("ant", E_ANT), ("pig", E_PIG), ("octo", E_OCTO1), ("bird", E_BIRD1),
            ("fish", E_FISH), ("troop", E_TROOP), ("thwomp", E_THWOMP1),
            ("wario", E_WARIO1), ("star", I_STAR), ("q", T_Q),
        ];
        for (name, s) in all {
            assert_eq!(s.px.len(), s.h, "height {}", name);
            for r in s.px { assert!(r.chars().count() <= s.w + 1, "width {} row {}", name, r); }
        }
    }
}
